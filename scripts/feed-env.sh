#!/usr/bin/env bash
#
# Write feed/.env for a local run against Mezo testnet, with the publisher's
# key taken straight out of its keystore and never shown.
#
# This is the file the VPS will hold at /srv/oucan/secrets/projects/
# leekdefi-feed.env with mode 0600. Writing the same thing locally is how the
# feed gets rehearsed against the real chain before any DNS or deploy work:
# same code, same key, same oracles, one machine instead of two.
#
# The key is piped from `cast wallet decrypt-keystore` directly into the file.
# It is never echoed, never a command-line argument, and never in your shell
# history. The file is created 0600 before anything is written to it, and
# feed/.gitignore already ignores it - checked below rather than assumed,
# because "I thought it was ignored" is how keys reach a public repository.
#
set -euo pipefail
cd "$(dirname "$0")/.."

ACCOUNT=${ACCOUNT:-leek-publisher}
ENV_FILE=feed/.env

# The live deployment, from ADDRESSES.md.
ORACLE_GOLOGGLE=0x7fCb1ed8d6fAaEF00AA5A0104A062299ab7D5BF6
ORACLE_AMEZON=0x5Ed8205bA3DC7075099cFC4b2D4b7f2fF8a9cf9D
RPC_URL=https://rpc.test.mezo.org
CHAIN_ID=31611

git check-ignore -q "$ENV_FILE" || {
  echo "STOP: $ENV_FILE is not git-ignored. Refusing to write a key there." >&2
  exit 1
}

if [[ -f "$ENV_FILE" ]]; then
  read -r -p "$ENV_FILE exists. Overwrite? Type yes: " answer
  [[ "$answer" == "yes" ]] || { echo "left alone"; exit 0; }
fi

ADDR=$(cast wallet address --account "$ACCOUNT")
echo "publisher $ADDR"

# The key is captured and checked BEFORE the file exists.
#
# Writing first and validating afterwards would be the wrong order: the
# keystore prompt could print to stdout, and a prompt captured in place of a
# key would then have been written to disk before anything noticed. So: take
# it, match it against the exact shape a key has, and only then create a file.
KEY=$(cast wallet decrypt-keystore "$ACCOUNT" | tr -d '\r' | grep -oE '0x[0-9a-fA-F]{64}' | head -1)
[[ "$KEY" =~ ^0x[0-9a-fA-F]{64}$ ]] || {
  echo "STOP: no 32-byte key came out of the keystore. Nothing was written." >&2
  exit 1
}

# Created empty and locked down first: a key must never exist in a
# world-readable file, not even for the instant between write and chmod.
install -m 600 /dev/null "$ENV_FILE"

{
  echo "# Local rehearsal of the VPS feed. Generated by scripts/feed-env.sh."
  echo "# Holds a private key: 0600, git-ignored, and not to be copied around."
  echo "PUBLISHER_PRIVATE_KEY=$KEY"
  echo "ORACLE_GOLOGGLE=$ORACLE_GOLOGGLE"
  echo "ORACLE_AMEZON=$ORACLE_AMEZON"
  echo "RPC_URL=$RPC_URL"
  echo "CHAIN_ID=$CHAIN_ID"
  echo "# Publishing policy: look every 60s, publish on a 50 bps move, and"
  echo "# publish anyway every 30 minutes so the feed never reads as stale."
  echo "INTERVAL_SECONDS=60"
  echo "HEARTBEAT_SECONDS=1800"
  echo "THRESHOLD_BPS=50"
  echo "HTTP_PORT=8787"
  echo "# 0: real prices from the source. The VPS runs it this way."
  echo "SYNTHETIC=0"
} > "$ENV_FILE"

unset KEY

# Proof it landed, without the key ever becoming an argument.
#
# The obvious check - `cast wallet address --private-key $(grep ...)` - puts
# the key in a command line, which is visible in `ps` and is the single thing
# this script exists to avoid. `--private-key` has no environment variable
# either. So the file is read by a short node program that derives the address
# in process and prints only that: the key stays in that process's memory and
# reaches no argv, no log and no terminal.
#
# Skipped, with a note, when the feed's dependencies are not installed yet;
# the first publish would catch a wrong key anyway, just an hour later.
if [[ -d feed/node_modules/viem ]]; then
  DERIVED=$(cd feed && node --experimental-strip-types --disable-warning=ExperimentalWarning -e '
    const fs = require("node:fs");
    const line = fs.readFileSync(".env", "utf8").split("\n").find((l) => l.startsWith("PUBLISHER_PRIVATE_KEY="));
    const key = line.slice("PUBLISHER_PRIVATE_KEY=".length).trim();
    import("viem/accounts").then(({ privateKeyToAccount }) => console.log(privateKeyToAccount(key).address));
  ')
  if [[ "${DERIVED,,}" != "${ADDR,,}" ]]; then
    shred -u "$ENV_FILE"
    echo "STOP: the key in the file derives to $DERIVED, not $ADDR. File removed." >&2
    exit 1
  fi
  echo "wrote $ENV_FILE (mode $(stat -c '%a' "$ENV_FILE"), key derives to $DERIVED)"
else
  echo "wrote $ENV_FILE (mode $(stat -c '%a' "$ENV_FILE"))"
  echo "   not derived-checked: run 'cd feed && npm ci' first if you want that check"
fi
cat <<NEXT

== run it

  cd feed && npm ci && npm start

  Then watch, in another terminal:

    curl -s localhost:8787/prices | python3 -m json.tool
    cast call $ORACLE_GOLOGGLE "latestRoundData()(uint80,int256,uint256,uint256,uint80)" \\
      --rpc-url $RPC_URL

  The round number should climb, and the answer should walk towards the index
  value in steps no larger than 20% - the oracle's own bound, which is why a
  first run from 200 towards ~100 takes several rounds rather than one.

  Explorer: https://explorer.test.mezo.org/address/$ORACLE_GOLOGGLE
NEXT
